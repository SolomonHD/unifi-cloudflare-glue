"""Offline, cooperative ownership/ledger protocol; deliberately no network adapter.

The injected transport must be independently qualified against the exact binding.
Its versions are opaque CAS tokens, not timestamps. A successful write means the
object is durable; an exception may mean it committed. There are no retries,
expiry, deletion or automatic takeover operations here. Explicit cleanup recovery
requires operator-established prior termination/exclusion and exact generation
evidence, preserving the unresolved original ledger in an immutable snapshot.

One maintenance object contains both claim and ledger, avoiding split-object
commit races. It serializes all participating runs in this dedicated prefix and
is normally replaced only after verified immutable completion history. This API
does not observe termination, state, DNS effects or live backend qualification.
Checks cannot fence requests already sent or writers bypassing this protocol.
"""

import json
import re
from dataclasses import asdict, dataclass, replace
from typing import Literal, NoReturn, Protocol, cast
from urllib.parse import urlsplit

from .canary_identity import ZONE_NAME, record_name, validate_run_prefix

Phase = Literal[
    "initialize",
    "create",
    "create_api",
    "create_dns",
    "validate",
    "update",
    "update_api",
    "update_dns",
    "plan",
    "cleanup_state",
    "destroy",
    "absence",
]
Outcome = Literal["succeeded", "failed", "unknown"]
_PHASES = {
    "initialize",
    "create",
    "create_api",
    "create_dns",
    "validate",
    "update",
    "update_api",
    "update_dns",
    "plan",
    "cleanup_state",
    "destroy",
    "absence",
}
_OUTCOMES = {"succeeded", "failed", "unknown"}


class StoreError(RuntimeError):
    """Sanitized fail-closed protocol error, never a provider response."""


class PreconditionFailed(Exception):
    """Transport reports a definitive rejected conditional write, not success."""


@dataclass(frozen=True)
class StoreBinding:
    endpoint: str
    region: str
    bucket: str
    prefix: str
    runtime_identity: str

    def validate(self) -> None:
        try:
            url = urlsplit(self.endpoint)
            valid_endpoint = (
                url.scheme == "https"
                and bool(url.hostname)
                and url.username is None
                and url.password is None
                and not url.query
                and not url.fragment
                and url.path in ("", "/")
            )
        except ValueError:
            valid_endpoint = False
        if (
            not valid_endpoint
            or not self.region
            or not self.bucket
            or not self.runtime_identity
            or not self.prefix
            or self.prefix.startswith("/")
            or not self.prefix.endswith("/")
            or any(part in ("", ".", "..") for part in self.prefix[:-1].split("/"))
        ):
            raise StoreError("Invalid protected-store binding")


@dataclass(frozen=True)
class Qualification:
    """Externally supplied attestations, not evidence generated by this module.

    runtime_identity must pin the reviewed transport/backend/runtime tuple. Flags
    default closed; neither an S3-compatible URL nor setting these flags qualifies
    a backend. The caller must retain the actual separately authorized evidence.
    """

    binding: StoreBinding
    conditional_create: bool = False
    conditional_update: bool = False
    durable_readback: bool = False
    opaque_versions: bool = False
    state_locking: bool = False
    encryption: bool = False
    restricted_access: bool = False
    unresolved_retention: bool = False
    writer_exclusion: bool = False

    def require(self, binding: StoreBinding) -> None:
        binding.validate()
        if self.binding != binding or not all(
            flag is True
            for flag in (
                self.conditional_create,
                self.conditional_update,
                self.durable_readback,
                self.opaque_versions,
                self.state_locking,
                self.encryption,
                self.restricted_access,
                self.unresolved_retention,
                self.writer_exclusion,
            )
        ):
            raise StoreError("Protected-store qualification required")


@dataclass(frozen=True)
class RunIdentity:
    run_prefix: str
    revision: str
    zone_id: str
    zone_name: str
    intended_records: tuple[tuple[str, str], ...]

    def validate(self) -> None:
        try:
            validate_run_prefix(self.run_prefix)
            valid = (
                re.fullmatch(r"[0-9a-f]{40}", self.revision) is not None
                and re.fullmatch(r"[0-9a-f]{32}", self.zone_id) is not None
                and self.zone_name == ZONE_NAME
                and self.intended_records
                == (
                    (record_name(self.run_prefix, "txt"), "TXT"),
                    (record_name(self.run_prefix, "cname"), "CNAME"),
                )
            )
        except (ValueError, TypeError):
            valid = False
        if not valid:
            raise StoreError("Invalid immutable canary identity")


@dataclass(frozen=True)
class Receipt:
    phase: Phase
    state_generation: str
    outcome: Outcome | None = None
    resulting_state_generation: str | None = None


@dataclass(frozen=True)
class CompletedPointer:
    key: str
    version: str
    claim_version: str


@dataclass(frozen=True)
class RecoveryAuthorization:
    run: RunIdentity
    expected_claim_version: str
    expected_generation: int
    observed_state_generation: str
    prior_writer_terminated: bool
    external_writer_exclusion: bool
    evidence_id: str


@dataclass(frozen=True)
class RecoveryPointer:
    key: str
    version: str
    claim_version: str
    generation: int


@dataclass(frozen=True)
class Ledger:
    run: RunIdentity
    owner: str
    generation: int
    state_generation: str
    receipts: tuple[Receipt, ...] = ()
    completed: CompletedPointer | None = None
    predecessor: CompletedPointer | None = None
    recovery: RecoveryPointer | None = None


@dataclass(frozen=True)
class StoredLedger:
    ledger: Ledger
    version: str


@dataclass(frozen=True)
class CompletedReceipt:
    ledger: Ledger
    claim_version: str


@dataclass(frozen=True)
class StoredArchive:
    receipt: CompletedReceipt
    version: str


@dataclass(frozen=True)
class RecoverySnapshot:
    ledger: Ledger
    claim_version: str
    recovery_owner: str
    authorization: RecoveryAuthorization


@dataclass(frozen=True)
class StoredRecoverySnapshot:
    snapshot: RecoverySnapshot
    version: str


def _token(value: object) -> bool:
    return (
        type(value) is str
        and 0 < len(value) <= 1024
        and all(32 <= ord(char) <= 126 for char in value)
    )


def _require_cleanup(ledger: Ledger) -> None:
    if (
        len(ledger.receipts) < 2
        or any(receipt.outcome not in ("succeeded", "failed") for receipt in ledger.receipts)
        or ledger.receipts[-1].phase != "absence"
        or ledger.receipts[-1].outcome != "succeeded"
        or ledger.receipts[-2].phase != "destroy"
        or ledger.receipts[-2].outcome != "succeeded"
        or ledger.receipts[-1].resulting_state_generation != ledger.state_generation
    ):
        raise StoreError("Verified cleanup required")


def validate_ledger(ledger: Ledger) -> None:
    """Validate the bounded trusted schema, including generation/receipt continuity."""
    try:
        if type(ledger) is not Ledger or type(ledger.run) is not RunIdentity:
            raise ValueError
        ledger.run.validate()
        if (
            not _token(ledger.owner)
            or not _token(ledger.state_generation)
            or type(ledger.generation) is not int
            or type(ledger.receipts) is not tuple
            or len(ledger.receipts) > 128
        ):
            raise ValueError
        generation = 0
        if ledger.recovery is not None:
            recovery_pointer = ledger.recovery
            if (
                type(recovery_pointer) is not RecoveryPointer
                or not _token(recovery_pointer.key)
                or not _token(recovery_pointer.version)
                or not _token(recovery_pointer.claim_version)
                or type(recovery_pointer.generation) is not int
                or not 1 <= recovery_pointer.generation <= 256
                or recovery_pointer.key.startswith("/")
                or any(part in ("", ".", "..") for part in recovery_pointer.key.split("/"))
                or not recovery_pointer.key.endswith("/recovery.json")
            ):
                raise ValueError
            generation = recovery_pointer.generation + 1
        previous = None
        for index, receipt in enumerate(ledger.receipts):
            if (
                type(receipt) is not Receipt
                or receipt.phase not in _PHASES
                or not _token(receipt.state_generation)
                or (previous is not None and receipt.state_generation != previous)
                or (
                    ledger.recovery is not None
                    and receipt.phase not in ("cleanup_state", "destroy", "absence")
                )
            ):
                raise ValueError
            generation += 1
            if receipt.outcome is None:
                if (
                    index != len(ledger.receipts) - 1
                    or receipt.resulting_state_generation is not None
                ):
                    raise ValueError
                previous = receipt.state_generation
            else:
                if receipt.outcome not in _OUTCOMES or not _token(
                    receipt.resulting_state_generation
                ):
                    raise ValueError
                if receipt.outcome == "unknown" and index != len(ledger.receipts) - 1:
                    raise ValueError
                generation += 1
                previous = receipt.resulting_state_generation
        if previous is not None and previous != ledger.state_generation:
            raise ValueError
        for pointer in (ledger.completed, ledger.predecessor):
            if pointer is not None and (
                type(pointer) is not CompletedPointer
                or not _token(pointer.key)
                or not _token(pointer.version)
                or not _token(pointer.claim_version)
                or pointer.key.startswith("/")
                or any(part in ("", ".", "..") for part in pointer.key.split("/"))
                or not pointer.key.endswith("/completed.json")
            ):
                raise ValueError
        if ledger.completed is not None:
            _require_cleanup(ledger)
            generation += 1
        if ledger.generation != generation:
            raise ValueError
    except Exception:
        raise StoreError("Invalid protected ledger schema") from None


def validate_archive(receipt: CompletedReceipt) -> None:
    try:
        if type(receipt) is not CompletedReceipt or not _token(receipt.claim_version):
            raise ValueError
        validate_ledger(receipt.ledger)
        if receipt.ledger.completed is not None:
            raise ValueError
        _require_cleanup(receipt.ledger)
    except Exception:
        raise StoreError("Invalid completed archive schema") from None


def validate_recovery_authorization(authorization: RecoveryAuthorization) -> None:
    try:
        if type(authorization) is not RecoveryAuthorization:
            raise ValueError
        authorization.run.validate()
        if (
            not _token(authorization.expected_claim_version)
            or type(authorization.expected_generation) is not int
            or not 1 <= authorization.expected_generation <= 256
            or not _token(authorization.observed_state_generation)
            or authorization.prior_writer_terminated is not True
            or authorization.external_writer_exclusion is not True
            or not _token(authorization.evidence_id)
            or not authorization.evidence_id.strip()
        ):
            raise ValueError
    except Exception:
        raise StoreError("Invalid explicit recovery authorization") from None


def validate_recovery_snapshot(snapshot: RecoverySnapshot) -> None:
    try:
        if type(snapshot) is not RecoverySnapshot:
            raise ValueError
        validate_ledger(snapshot.ledger)
        validate_recovery_authorization(snapshot.authorization)
        auth = snapshot.authorization
        if (
            not _token(snapshot.recovery_owner)
            or snapshot.recovery_owner == snapshot.ledger.owner
            or snapshot.claim_version != auth.expected_claim_version
            or snapshot.ledger.run != auth.run
            or snapshot.ledger.generation != auth.expected_generation
            or snapshot.ledger.completed is not None
            or snapshot.ledger.recovery is not None
            or not snapshot.ledger.receipts
            or not (
                snapshot.ledger.receipts[-1].outcome in (None, "unknown")
                or (
                    snapshot.ledger.receipts[-1].outcome == "failed"
                    and snapshot.ledger.receipts[-1].phase
                    in {"cleanup_state", "destroy", "absence"}
                )
            )
        ):
            raise ValueError
    except Exception:
        raise StoreError("Invalid immutable recovery snapshot") from None


_MAX_JSON_BYTES = 262144


def _object(value: object, keys: set[str]) -> dict[str, object]:
    if type(value) is not dict or set(value) != keys:
        raise ValueError
    return cast(dict[str, object], value)


def _decode_run(value: object) -> RunIdentity:
    run = _object(value, {"run_prefix", "revision", "zone_id", "zone_name", "intended_records"})
    records = run["intended_records"]
    if type(records) is not list or len(records) != 2:
        raise ValueError
    if any(type(record) is not list or len(record) != 2 for record in records):
        raise ValueError
    identity = RunIdentity(
        cast(str, run["run_prefix"]),
        cast(str, run["revision"]),
        cast(str, run["zone_id"]),
        cast(str, run["zone_name"]),
        tuple(tuple(record) for record in records),
    )
    identity.validate()
    return identity


def _decode_ledger(value: object) -> Ledger:
    if type(value) is dict and "recovery" not in value:
        # Concrete schema-1 ledgers persisted by the first pilot lack this field.
        value = {**value, "recovery": None}
    row = _object(
        value,
        {
            "run",
            "owner",
            "generation",
            "state_generation",
            "receipts",
            "completed",
            "predecessor",
            "recovery",
        },
    )
    identity = _decode_run(row["run"])
    receipts = row["receipts"]
    if type(receipts) is not list or len(receipts) > 128:
        raise ValueError
    parsed = tuple(
        Receipt(**_object(item, {"phase", "state_generation", "outcome", "resulting_state_generation"}))  # type: ignore[arg-type]
        for item in receipts
    )
    pointers = []
    for name in ("completed", "predecessor"):
        item = row[name]
        pointer = None if item is None else _object(item, {"key", "version", "claim_version"})
        pointers.append(
            None
            if pointer is None
            else CompletedPointer(
                cast(str, pointer["key"]),
                cast(str, pointer["version"]),
                cast(str, pointer["claim_version"]),
            )
        )
    ledger = Ledger(
        identity,
        cast(str, row["owner"]),
        cast(int, row["generation"]),
        cast(str, row["state_generation"]),
        parsed,
        pointers[0],
        pointers[1],
        recovery=(
            None
            if row["recovery"] is None
            else RecoveryPointer(**_object(row["recovery"], {"key", "version", "claim_version", "generation"}))  # type: ignore[arg-type]
        ),
    )
    validate_ledger(ledger)
    return ledger


def _json_object(pairs: list[tuple[str, object]]) -> dict[str, object]:
    result: dict[str, object] = {}
    for key, value in pairs:
        if key in result:
            raise ValueError
        result[key] = value
    return result


def _decode(payload: bytes, kind: str) -> object:
    if type(payload) is not bytes or len(payload) > _MAX_JSON_BYTES:
        raise ValueError
    row = _object(
        json.loads(payload.decode("utf-8"), object_pairs_hook=_json_object),
        {"schema", "kind", "body"},
    )
    if type(row["schema"]) is not int or row["schema"] != 1 or row["kind"] != kind:
        raise ValueError
    return row["body"]


def _encode(value: Ledger | CompletedReceipt | RecoverySnapshot, kind: str) -> bytes:
    body = asdict(value)
    ledger = body if kind == "ledger" else body["ledger"]
    if ledger["recovery"] is None:
        # Preserve the exact original schema shape, including archived prior claims.
        ledger.pop("recovery")
    payload = json.dumps(
        {"schema": 1, "kind": kind, "body": body},
        sort_keys=True,
        separators=(",", ":"),
        allow_nan=False,
    ).encode("utf-8")
    if len(payload) > _MAX_JSON_BYTES:
        raise ValueError
    return payload


def encode_ledger(ledger: Ledger) -> bytes:
    try:
        validate_ledger(ledger)
        return _encode(ledger, "ledger")
    except Exception:
        raise StoreError("Invalid protected ledger encoding") from None


def decode_ledger(payload: bytes) -> Ledger:
    try:
        return _decode_ledger(_decode(payload, "ledger"))
    except Exception:
        raise StoreError("Invalid protected ledger encoding") from None


def encode_archive(receipt: CompletedReceipt) -> bytes:
    try:
        validate_archive(receipt)
        return _encode(receipt, "completed")
    except Exception:
        raise StoreError("Invalid completed archive encoding") from None


def decode_archive(payload: bytes) -> CompletedReceipt:
    try:
        row = _object(_decode(payload, "completed"), {"ledger", "claim_version"})
        receipt = CompletedReceipt(_decode_ledger(row["ledger"]), cast(str, row["claim_version"]))
        validate_archive(receipt)
        return receipt
    except Exception:
        raise StoreError("Invalid completed archive encoding") from None


def encode_recovery_snapshot(snapshot: RecoverySnapshot) -> bytes:
    try:
        validate_recovery_snapshot(snapshot)
        return _encode(snapshot, "recovery")
    except Exception:
        raise StoreError("Invalid recovery snapshot encoding") from None


def decode_recovery_snapshot(payload: bytes) -> RecoverySnapshot:
    try:
        row = _object(
            _decode(payload, "recovery"),
            {"ledger", "claim_version", "recovery_owner", "authorization"},
        )
        auth = _object(
            row["authorization"],
            {
                "run",
                "expected_claim_version",
                "expected_generation",
                "observed_state_generation",
                "prior_writer_terminated",
                "external_writer_exclusion",
                "evidence_id",
            },
        )
        authorization = RecoveryAuthorization(**{**auth, "run": _decode_run(auth["run"])})  # type: ignore[arg-type]
        snapshot = RecoverySnapshot(
            _decode_ledger(row["ledger"]),
            cast(str, row["claim_version"]),
            cast(str, row["recovery_owner"]),
            authorization,
        )
        validate_recovery_snapshot(snapshot)
        return snapshot
    except Exception:
        raise StoreError("Invalid recovery snapshot encoding") from None


class Transport(Protocol):
    """No implicit retries; each write is one atomic conditional operation.

    get returns None only for authoritative absence, never for access/backend
    errors. Implementations must validate decoded schema and raise on malformed
    objects. Write results must include the durable object and its opaque version.
    No concrete Wasabi semantics are asserted by this interface.
    """

    def get(self, binding: StoreBinding, key: str) -> StoredLedger | None: ...

    def create_if_absent(self, binding: StoreBinding, key: str, ledger: Ledger) -> StoredLedger: ...

    def update_if_version(
        self, binding: StoreBinding, key: str, ledger: Ledger, expected_version: str
    ) -> StoredLedger: ...

    def create_archive(
        self, binding: StoreBinding, key: str, receipt: CompletedReceipt
    ) -> StoredArchive:
        """Immutable conditional create; an existing key MUST NOT be overwritten."""
        ...

    def get_archive(self, binding: StoreBinding, key: str) -> StoredArchive | None: ...

    def create_recovery_snapshot(
        self, binding: StoreBinding, key: str, snapshot: RecoverySnapshot
    ) -> StoredRecoverySnapshot: ...

    def get_recovery_snapshot(
        self, binding: StoreBinding, key: str
    ) -> StoredRecoverySnapshot | None: ...


class CanaryStore:
    """One writer session; any ownership/backend uncertainty permanently blocks it.

    The caller supplies authoritative state generations at each boundary. A
    generation token alone does not observe Terraform or establish writer death.
    check_before_effect must be called immediately before issuing an effect, and
    record_result only after authoritative observation. An incomplete intent is
    uncertain on restart and cannot be resumed by claiming again.
    """

    def __init__(
        self, transport: Transport, binding: StoreBinding, qualification: Qualification
    ) -> None:
        self._transport = transport
        self._binding = binding
        self._qualification = qualification
        self._current: StoredLedger | None = None
        self._attempted: Ledger | None = None
        self._archive_attempted: CompletedReceipt | None = None
        self._archive_retained: StoredArchive | None = None
        self._recovery_attempted: RecoverySnapshot | None = None
        self._recovery_retained: StoredRecoverySnapshot | None = None
        self._blocked = False
        self._effect_checked = False

    @property
    def key(self) -> str:
        return self._binding.prefix + "maintenance.json"

    @property
    def retained(self) -> StoredLedger | None:
        """Last confirmed receipt; not proof of current ownership or write failure."""
        return self._current

    @property
    def attempted(self) -> Ledger | None:
        """Last write proposal, retained even when commit/confirmation is unknown."""
        return self._attempted

    @property
    def archive_attempted(self) -> CompletedReceipt | None:
        return self._archive_attempted

    @property
    def archive_retained(self) -> StoredArchive | None:
        return self._archive_retained

    @property
    def recovery_attempted(self) -> RecoverySnapshot | None:
        return self._recovery_attempted

    @property
    def recovery_retained(self) -> StoredRecoverySnapshot | None:
        return self._recovery_retained

    def _gate(self) -> None:
        if self._blocked:
            raise StoreError("Session blocked; explicit operator reconciliation required")
        self._qualification.require(self._binding)

    def _stop(self, message: str) -> NoReturn:
        self._blocked = True
        raise StoreError(message) from None

    def claim(self, owner: str, run: RunIdentity, state_generation: str) -> StoredLedger:
        self._gate()
        run.validate()
        if not owner or not state_generation or self._current is not None:
            raise StoreError("Invalid claim request")
        proposed = Ledger(run, owner, 0, state_generation)
        validate_ledger(proposed)
        self._attempted = proposed
        try:
            stored = self._transport.create_if_absent(self._binding, self.key, proposed)
        except PreconditionFailed:
            return self._claim_successor(proposed)
        except Exception:
            self._stop("Claim outcome unknown; explicit operator reconciliation required")
        if (
            type(stored) is not StoredLedger
            or stored.ledger != proposed
            or not _token(stored.version)
        ):
            self._stop("Claim confirmation invalid; retain recovery identity")
        self._current = stored
        return self._check(state_generation)

    def _archive_key(self, run: RunIdentity) -> str:
        return self._binding.prefix + "runs/" + run.run_prefix + "/completed.json"

    def _recovery_key(self, run: RunIdentity) -> str:
        return self._binding.prefix + "runs/" + run.run_prefix + "/recovery.json"

    def recover(
        self, owner: str, authorization: RecoveryAuthorization, observed_state_generation: str
    ) -> StoredLedger:
        """Transfer only explicitly reconciled unresolved ownership, never replay it.

        The caller must freshly observe the exact state generation and establish
        prior termination and external writer exclusion before invoking this API.
        No age, lease or normal-claim failure establishes those proofs.
        """
        self._gate()
        validate_recovery_authorization(authorization)
        if self._current is not None or not _token(owner):
            raise StoreError("New explicit recovery session required")
        if observed_state_generation != authorization.observed_state_generation:
            self._stop("Observed recovery state generation changed")
        try:
            previous = self._transport.get(self._binding, self.key)
            if type(previous) is not StoredLedger:
                self._stop("Exact prior recovery claim required")
            snapshot = RecoverySnapshot(previous.ledger, previous.version, owner, authorization)
            validate_recovery_snapshot(snapshot)
            self._current = previous
            self._recovery_attempted = snapshot
            key = self._recovery_key(previous.ledger.run)
            archived = self._transport.create_recovery_snapshot(self._binding, key, snapshot)
            if (
                type(archived) is not StoredRecoverySnapshot
                or archived.snapshot != snapshot
                or not _token(archived.version)
            ):
                self._stop("Recovery snapshot confirmation invalid")
            self._recovery_retained = archived
            if self._transport.get_recovery_snapshot(self._binding, key) != archived:
                self._stop("Recovery snapshot readback invalid")
            if self._transport.get(self._binding, self.key) != previous:
                self._stop("Prior recovery claim changed")
        except Exception:
            self._stop("Recovery snapshot or claim unconfirmed; retain original unknown history")
        proposed = replace(
            previous.ledger,
            owner=owner,
            generation=previous.ledger.generation + 1,
            state_generation=observed_state_generation,
            receipts=(),
            recovery=RecoveryPointer(
                key, archived.version, previous.version, previous.ledger.generation
            ),
        )
        return self._write(proposed)

    def _verify_recovery(self, ledger: Ledger) -> None:
        pointer = ledger.recovery
        if pointer is None:
            return
        try:
            if pointer.key != self._recovery_key(ledger.run):
                raise ValueError
            archived = self._transport.get_recovery_snapshot(self._binding, pointer.key)
            if type(archived) is not StoredRecoverySnapshot:
                raise ValueError
            validate_recovery_snapshot(archived.snapshot)
            snapshot = archived.snapshot
            initial_state = (
                ledger.receipts[0].state_generation if ledger.receipts else ledger.state_generation
            )
            if (
                archived.version != pointer.version
                or snapshot.claim_version != pointer.claim_version
                or snapshot.ledger.generation != pointer.generation
                or snapshot.ledger.run != ledger.run
                or snapshot.ledger.predecessor != ledger.predecessor
                or snapshot.recovery_owner != ledger.owner
                or snapshot.authorization.observed_state_generation != initial_state
            ):
                raise ValueError
            self._recovery_retained = archived
        except Exception:
            self._stop("Recovery history unavailable or invalid; retain original unknown history")

    def _claim_successor(self, proposed: Ledger) -> StoredLedger:
        try:
            previous = self._transport.get(self._binding, self.key)
            if previous is None:
                self._stop("Existing claim unavailable; no automatic takeover")
            validate_ledger(previous.ledger)
            if not _token(previous.version):
                self._stop("Existing claim version invalid")
            self._current = previous
            pointer = previous.ledger.completed
            if pointer is None:
                self._stop("Existing ownership claim; no automatic takeover")
            if (
                pointer.key != self._archive_key(previous.ledger.run)
                or previous.ledger.run.run_prefix == proposed.run.run_prefix
            ):
                self._stop("Completed claim identity mismatch")
            archive = self._transport.get_archive(self._binding, pointer.key)
            if archive is None:
                self._stop("Completed history missing")
            validate_archive(archive.receipt)
            expected = replace(
                previous.ledger, generation=previous.ledger.generation - 1, completed=None
            )
            if (
                archive.version != pointer.version
                or archive.receipt.ledger != expected
                or archive.receipt.claim_version != pointer.claim_version
                or archive.receipt.claim_version == previous.version
            ):
                self._stop("Completed history confirmation invalid")
            self._verify_recovery(previous.ledger)
        except Exception:
            self._stop(
                "Completed history unavailable or invalid; no automatic takeover; retain recovery identity"
            )
        # Preserve the verified predecessor even if the successor CAS is uncertain.
        self._current = previous
        self._archive_retained = archive
        return self._write(replace(proposed, predecessor=pointer))

    def complete_verified(self, owner: str, state_generation: str) -> StoredLedger:
        """Archive verified cleanup before marking the active claim completed.

        The absence result must attest both exact-name DNS absence and reconciled
        empty state. This method verifies the durable evidence, not DNS itself.
        """
        current = self._check(state_generation)
        if current.ledger.owner != owner or current.ledger.completed is not None:
            self._stop("Invalid completion owner or already completed")
        try:
            validate_ledger(current.ledger)
            _require_cleanup(current.ledger)
        except StoreError:
            self._stop("Verified cleanup required before completion")
        self._verify_recovery(current.ledger)
        receipt = CompletedReceipt(current.ledger, current.version)
        self._archive_attempted = receipt
        key = self._archive_key(current.ledger.run)
        try:
            archive = self._transport.create_archive(self._binding, key, receipt)
            if (
                type(archive) is not StoredArchive
                or archive.receipt != receipt
                or not _token(archive.version)
            ):
                self._stop("Archive confirmation invalid")
            self._archive_retained = archive
            if self._transport.get_archive(self._binding, key) != archive:
                self._stop("Archive readback invalid")
        except Exception:
            self._stop("Archive outcome unknown or invalid; retain recovery identity")
        self._check(state_generation)
        return self._write(
            replace(
                current.ledger,
                generation=current.ledger.generation + 1,
                completed=CompletedPointer(key, archive.version, current.version),
            )
        )

    def _check(self, state_generation: str) -> StoredLedger:
        self._gate()
        if self._current is None:
            raise StoreError("Ownership claim required")
        try:
            observed = self._transport.get(self._binding, self.key)
        except Exception:
            self._stop("Ownership unavailable; retain recovery identity")
        # Equality checks owner, generation, immutable identity AND ledger body.
        if (
            type(observed) is not StoredLedger
            or observed != self._current
            or state_generation != self._current.ledger.state_generation
        ):
            self._stop("Ownership or generation changed; retain recovery identity")
        return self._current

    def _write(self, ledger: Ledger) -> StoredLedger:
        assert self._current is not None
        validate_ledger(ledger)
        self._attempted = ledger
        try:
            stored = self._transport.update_if_version(
                self._binding, self.key, ledger, self._current.version
            )
        except PreconditionFailed:
            self._stop("Ownership precondition failed; retain recovery identity")
        except Exception:
            self._stop("Receipt outcome unknown; retain recovery identity")
        if (
            type(stored) is not StoredLedger
            or stored.ledger != ledger
            or not _token(stored.version)
            or stored.version == self._current.version
        ):
            self._stop("Receipt confirmation invalid; retain recovery identity")
        self._current = stored
        return self._check(ledger.state_generation)

    def check_ownership(self, state_generation: str) -> StoredLedger:
        """Revalidate a known claim without authorizing another effect."""
        return self._check(state_generation)

    def begin_intent(self, phase: Phase, state_generation: str) -> StoredLedger:
        current = self._check(state_generation).ledger
        if current.completed is not None:
            self._stop("Completed session cannot issue further effects")
        if phase not in _PHASES:
            raise StoreError("Unsupported canary phase")
        if current.recovery is not None and phase not in ("cleanup_state", "destroy", "absence"):
            self._stop("Recovery session permits cleanup phases only")
        if current.receipts and current.receipts[-1].outcome in (None, "unknown"):
            self._stop("Uncertain prior effect; explicit operator reconciliation required")
        self._effect_checked = False
        return self._write(
            replace(
                current,
                generation=current.generation + 1,
                receipts=(*current.receipts, Receipt(phase, state_generation)),
            )
        )

    def check_before_effect(self, state_generation: str) -> StoredLedger:
        stored = self._check(state_generation)
        if not stored.ledger.receipts or stored.ledger.receipts[-1].outcome is not None:
            raise StoreError("Durable pending intent required")
        if self._effect_checked:
            self._stop("Effect already issued; no implicit retry")
        self._effect_checked = True
        return stored

    def record_result(
        self, outcome: Outcome, state_generation: str, resulting_state_generation: str
    ) -> StoredLedger:
        current = self._check(state_generation).ledger
        if (
            not self._effect_checked
            or not current.receipts
            or current.receipts[-1].outcome is not None
            or outcome not in _OUTCOMES
            or not resulting_state_generation
        ):
            raise StoreError("Invalid phase result boundary")
        stored = self._write(
            replace(
                current,
                generation=current.generation + 1,
                state_generation=resulting_state_generation,
                receipts=(
                    *current.receipts[:-1],
                    replace(
                        current.receipts[-1],
                        outcome=outcome,
                        resulting_state_generation=resulting_state_generation,
                    ),
                ),
            )
        )
        self._effect_checked = False
        if outcome == "unknown":
            self._blocked = True
        return stored
